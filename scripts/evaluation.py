"""Generate the published evaluation solely from committed evidence."""
import json,subprocess,math
from pathlib import Path
def read(path):return json.loads(subprocess.check_output(["git","show","HEAD:"+path],text=True))
def quantile(a,q):
 if not a:return 0
 a=sorted(a);return a[max(0,math.ceil(q*len(a))-1)]

def summarize(b,file):
 times=[r["elapsed_ms"]/1000 for r in b["results"]]
 return {**b,"file":file,"code_commit":b.get("code_commit",b.get("implementation_commit","Not recorded in original evidence")),"median_seconds":quantile(times,.5),"p90_seconds":quantile(times,.9)}
files=subprocess.check_output(["git","ls-tree","-r","--name-only","HEAD","evidence/question-set"],text=True).splitlines()
batches={}
for f in files:
 if not f.endswith(".json") or f.endswith("/latest.json"):continue
 b=read(f)
 if "results" not in b:continue
 entry=summarize(b,f)
 old=batches.get(b["started_at"])
 if old and entry["code_commit"]=="Not recorded in original evidence":entry["code_commit"]=old["code_commit"]
 batches[b["started_at"]]=entry
history=sorted(batches.values(),key=lambda b:b["started_at"])
latest=next(b for b in reversed(history) if b["complete"] and len(b["results"])==25)
data={"latest":latest,"history":history,"step_timings":read("evidence/step-timings.json"),"amendments":read("evidence/question-amendments.json"),"reproduce":"npm run questions"}
Path("evidence/evaluation.json").write_text(json.dumps(data,indent=2)+"\n")
def esc(s):return str(s).replace("|","\\|").replace("\n"," ")
bt=chr(96)
lines=["# Fieldwork evaluation","","Generated by "+bt+"python3 scripts/evaluation.py"+bt+" from committed evidence only. Reproduce a live batch with "+bt+"npm run questions"+bt+".","","Latest full batch: "+str(latest["passed"])+"/25; median "+str(round(latest["median_seconds"],3))+" s; p90 "+str(round(latest["p90_seconds"],3))+" s.","","Code: "+latest["code_commit"],"Question SHA-256: "+latest["question_sha256"],"Date: "+latest["started_at"],"","## Every batch","","|Date|Passed|Rate|Median s|p90 s|Code|","|---|---:|---:|---:|---:|---|"]
for b in history:lines.append("|"+"|".join(map(esc,[b["started_at"],str(b["passed"])+"/"+str(b["total"]),str(round(b["rate"]*100,1))+"%",round(b["median_seconds"],3),round(b["p90_seconds"],3),b["code_commit"]]))+"|")
lines+=["","## Latest questions","","|Question|Expected|Actual|Seconds|Result|Failed acceptance lines|Answer|","|---|---|---|---:|---|---|---|"]
for r in latest["results"]:
 failed=[c["name"] for c in r.get("checks",[]) if not c["ok"]]
 lines.append("|"+"|".join(map(esc,[r["question"],r["expected"],r["status"],round(r["elapsed_ms"]/1000,3),"Passed"if r["passed"] else"Failed","; ".join(failed+r.get("reasons",[])),"[Run](https://fieldwork.38-49-216-59.sslip.io/a/"+r["run_id"]+")"]))+"|")
lines+=["","## Step timings","",data["step_timings"]["method"],"","|Batch|Step|Median s|p90 s|Models|","|---|---|---:|---:|---|"]
for b in data["step_timings"]["batches"]:
 for s in b["steps"]:lines.append("|"+"|".join(map(esc,[b["started_at"],s["step"],s["median_seconds"],s["p90_seconds"],", ".join(s["models"])or"Code"]))+"|")
lines+=["","## Amendments",""]
for a in data["amendments"]["amendments"]+data["amendments"]["grader_corrections"]:lines.append("- "+a["id"]+": "+a["reason"])
Path("evidence/EVAL.md").write_text("\n".join(lines)+"\n")
print(json.dumps({"batches":len(history),"latest_passed":latest["passed"],"latest":latest["started_at"]}))
